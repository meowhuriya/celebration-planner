"use client";

import { memo } from "react";
import type { Guest, SeatKey } from "@/lib/seating";

interface SeatingPrintViewProps {
  totalTables: number;
  seatsPerTable: number;
  guests: Guest[];
  assignments: Record<SeatKey, string>;
}

function SeatingPrintViewComponent({
  totalTables,
  seatsPerTable,
  guests,
  assignments,
}: SeatingPrintViewProps) {
  const guestMap = new Map(guests.map((g) => [g.id, g]));

  // Build table listing
  const tableData: Array<{
    tableNumber: number;
    seats: Array<{ seatIndex: number; guest?: Guest }>;
  }> = [];

  for (let t = 1; t <= totalTables; t++) {
    const seats: Array<{ seatIndex: number; guest?: Guest }> = [];
    for (let s = 0; s < seatsPerTable; s++) {
      const gId = assignments[`${t}-${s}`];
      seats.push({
        seatIndex: s + 1,
        guest: gId ? guestMap.get(gId) : undefined,
      });
    }
    tableData.push({ tableNumber: t, seats });
  }

  const seatedCount = Object.keys(assignments).length;

  return (
    <div className="hidden p-6 font-sans text-xs text-[#111111] print:block">
      <div className="mb-6 flex items-baseline justify-between border-b-2 border-[#111111] pb-3">
        <div>
          <h1 className="font-serif text-2xl font-bold">
            Official Event Seating Chart
          </h1>
          <p className="mt-1 text-xs text-[#5A5A5A]">
            Generated by Celebrate Event Planner · {totalTables} Tables ·{" "}
            {seatsPerTable} Seats per table
          </p>
        </div>
        <div className="text-right font-mono text-xs font-semibold">
          {seatedCount} of {guests.length} Guests Seated
        </div>
      </div>

      <div className="grid grid-cols-2 gap-6">
        {tableData.map((table) => {
          const filled = table.seats.filter((s) => s.guest).length;
          return (
            <div
              key={table.tableNumber}
              className="page-break-inside-avoid rounded-lg border border-[#D9D9D9] p-3"
            >
              <div className="mb-2 flex items-center justify-between border-b pb-1.5">
                <span className="font-serif text-sm font-bold">
                  Table {table.tableNumber}
                </span>
                <span className="font-mono text-[11px] text-[#5A5A5A]">
                  {filled} / {seatsPerTable} seats
                </span>
              </div>

              <ol className="space-y-1">
                {table.seats.map((seat) => (
                  <li
                    key={seat.seatIndex}
                    className="flex items-center justify-between border-b border-gray-100 py-0.5 last:border-none"
                  >
                    <span className="w-6 text-[11px] text-[#5A5A5A]">
                      #{seat.seatIndex}
                    </span>
                    <span className="flex-1 truncate font-medium">
                      {seat.guest ? seat.guest.name : "— Empty —"}
                    </span>
                    {seat.guest?.group && (
                      <span className="text-[10px] italic text-[#5A5A5A]">
                        {seat.guest.group}
                      </span>
                    )}
                  </li>
                ))}
              </ol>
            </div>
          );
        })}
      </div>

      <div className="mt-8 border-t pt-2 text-center text-[10px] text-[#767676]">
        Confidential guest list · Stored on device only · Printed for venue
        management
      </div>
    </div>
  );
}

export const SeatingPrintView = memo(SeatingPrintViewComponent);
